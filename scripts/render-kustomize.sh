#!/usr/bin/env bash
# Renders each component's workloads from its chart into components/<component>/generated.yaml.
#
# Usage:
#   scripts/render-kustomize.sh           # write
#   scripts/render-kustomize.sh --check   # fail if any generated.yaml would change
#
# A component is rendered when components/<component>/kustomize-values.yaml exists; its chart is
# charts/snapcd-<component>. Everything Helm adds to identify itself is stripped, so the output
# reads as plain manifests: the helm.sh/* and managed-by labels and the "# Source:" comments.
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"

MODE="write"
if [[ ${1:-} == "--check" ]]; then
    MODE="check"
fi

stale=0
for values in components/*/kustomize-values.yaml; do
    [[ -e "$values" ]] || continue
    component="$(basename "$(dirname "$values")")"
    chart="charts/snapcd-${component}"
    target="components/${component}/generated.yaml"

    rendered="$(
        {
            echo "# Generated by scripts/render-kustomize.sh from ${chart}. Do not edit; change the chart or kustomize-values.yaml."
            helm template "snapcd-${component}" "$chart" \
                --namespace "snapcd-${component}" \
                --values "$values"
        } | sed -E \
            -e '/^# Source: /d' \
            -e '/^[[:space:]]*helm\.sh\/[^:]*:/d' \
            -e '/^[[:space:]]*meta\.helm\.sh\/[^:]*:/d' \
            -e '/^[[:space:]]*app\.kubernetes\.io\/managed-by:/d'
    )"

    if [[ "$MODE" == "check" ]]; then
        if ! diff -u "$target" <(printf '%s\n' "$rendered") >/dev/null 2>&1; then
            echo "${target} is stale; run scripts/render-kustomize.sh" >&2
            diff -u "$target" <(printf '%s\n' "$rendered") >&2 || true
            stale=1
        fi
    else
        printf '%s\n' "$rendered" > "$target"
    fi
done

exit "$stale"
